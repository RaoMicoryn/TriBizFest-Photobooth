"use client";

import * as React from "react";
import { cn } from "@/components/ui/button";

type CardProps = React.HTMLAttributes<HTMLDivElement>;

const Card = React.forwardRef<HTMLDivElement, CardProps>(
  ({ className, ...props }, ref) => (
    <div
      ref={ref}
      className={cn(
        "card",
        className,
      )}
      {...props}
    />
  ),
);
Card.displayName = "Card";

